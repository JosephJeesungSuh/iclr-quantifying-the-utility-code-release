SCORE_PROMPT = """\
# Instruction
You are an expert evaluator. Your task is to evaluate the quality of the responses generated by AI models.
We will provide you with the user query and an AI-generated responses. You should first read the user query and the conversation history carefully for analyzing the task, and then evaluate the quality of the responses based on and rules provided below.

# Conversation between User and AI
## History
<|begin_of_history|>
{history}
<|end_of_history|>

## Current User Query
<|begin_of_query|>
{user_query}
<|end_of_query|>

## AI Response
<|begin_of_response|>
{model_output}
<|end_of_response|>

# Evaluation
## Checklist
<|begin_of_checklist|>
{checklist}
<|end_of_checklist|>
Please use this checklist to guide your evaluation, but do not limit your assessment to the checklist.

## Rules
You should compare the above response based on your analysis of the user queries and the conversation history.
You should first write down your analysis and the checklist that you used for the evaluation, and then provide your assessment according to the checklist.
The scores are in the range of 1~10, where 1 means the response is very poor and 10 means the response is perfect.
Here are more detailed criteria for the scores:

- Score 1~2: The response is very poor and does not make sense at all.
- Score 3~4: The response is poor and does not help user solve the problem in a meaningful way.
- Score 5~6: The response is fair but has some issues (e.g., factual errors, hallucinations, missing key information).
- Score 7~8: The response is good enough but could be improved in some ways.
- Score 9~10: The response is perfect and provides helpful information that can help user solve the problem.

## Output Format
First, please output your analysis for the model response, and then summarize your assessment to two aspects: "strengths" and "weaknesses"; Finally, please write down your rating for the assessment.

Please provide your evaluation results in the following json format by filling in the placeholders in []:
```
{{
"strengths": "[analysis for the strengths of the response]",
"weaknesses": "[analysis for the weaknesses of the response]",
"score": "[1~10]"
}}
```

IMPORTANT: You must output a valid JSON block with the "score" field set to exactly one integer from 1 to 10."""


def _extract_json_score(text: str) -> Optional[int]:
    """
    Extract the 'score' field from the judge's JSON response.
    Returns an integer 1-10 or None on failure.
    """
    code_block = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    raw = code_block.group(1) if code_block else text
    try:
        data = json.loads(raw)
        score_val = data.get("score", "")
        score_val = str(score_val).strip().strip('"').strip("'")
        return int(float(score_val))
    except (json.JSONDecodeError, ValueError, TypeError):
        pass

    # Fallback: regex for "score": "N" or "score": N
    m = re.search(r'"score"\s*:\s*"?(\d+(?:\.\d+)?)"?', raw)
    if m:
        return int(float(m.group(1)))

    return None


def judge_score(
    judge_client: OpenAI, judge_model: str,
    task: Dict,
    model_output: str,
    max_retries: int = 8,
) -> Dict:
    """
    Ask the judge to score a single model response individually.
    Returns a dict with 'raw_score', 'rescaled_score', 'raw_output',
    'usage', 'input_messages', and 'failed'.
    """
    checklist_str = "\n".join(f"- {q}" for q in task["checklist"])
    prompt = SCORE_PROMPT.format(
        history=task["history"],
        user_query=task["user_query"],
        model_output=model_output,
        checklist=checklist_str,
    )
    judge_messages = [{"role": "user", "content": prompt}]

    raw_score = None
    raw_output = ""
    judge_usage: Dict = {"prompt_tokens": None, "completion_tokens": None, "total_tokens": None}
    if judge_model.lower().startswith("gemini"):
        extra_kwargs: Dict = {"extra_body": {"reasoning_effort": "none"}}
    else:
        extra_kwargs = {}

    for _retry in range(max_retries):
        try:
            retry_temp = 0.0 if _retry == 0 else 0.3
            resp = judge_client.chat.completions.create(
                model=judge_model,
                messages=judge_messages,
                max_tokens=16384,
                temperature=retry_temp,
                **extra_kwargs,
            )
            raw_output = resp.choices[0].message.content or ""
            usage = resp.usage
            if usage:
                judge_usage = {
                    "prompt_tokens": usage.prompt_tokens,
                    "completion_tokens": usage.completion_tokens,
                    "total_tokens": usage.total_tokens,
                }
            extracted = _extract_json_score(raw_output)
            if extracted is not None and 1 <= extracted <= 10:
                raw_score = extracted
                break
            else:
                logger.warning("Judge retry %d/%d: could not extract valid score from output (first 2000 chars): %s",
                               _retry + 1, max_retries, raw_output[:2000])
        except Exception as e:
            logger.warning("Judge retry %d/%d error: %s", _retry + 1, max_retries, e)
            time.sleep(_retry * 2 + 0.5)

    failed = raw_score is None
    if failed:
        return {
            "raw_score": None,
            "rescaled_score": None,
            "raw_output": raw_output,
            "usage": judge_usage,
            "input_messages": judge_messages,
            "failed": True,
        }

    # Two rescalings reported in the paper:
    # 1. Table 2 uses raw_score * 10 (0-100 scale, e.g. GPT-4o = 65.3)
    # 2. Section 3.3 text describes S' = (S - 5) * 2 (-8 to +10 scale)
    score_100 = raw_score * 10
    rescaled_score = (raw_score - 5) * 2

    return {
        "raw_score": raw_score,
        "score_100": score_100,
        "rescaled_score": rescaled_score,
        "raw_output": raw_output,
        "usage": judge_usage,
        "input_messages": judge_messages,
        "failed": False,
    }


def evaluate_score(
    model: str,
    judge_model: str,
    port_model: int = 8000,
    port_judge: int = 8002,
    max_workers: int = 8,
    max_workers_gen: int = 8,
    max_tokens: int = 2048,
    output_dir: str = "results",
    n_tasks: Optional[int] = None,
    temperature: float = 0.0,
    top_p: Optional[float] = None,
    debug: bool = False,
) -> Dict:
    """
    Run WB-Score individual evaluation for a single model.
    Returns dict with 'summary' and per-task 'results'.
    """
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    client = _get_client(model, port_model)
    judge_client = _get_client(judge_model, port_judge)
    tasks = load_wildbench()
    if n_tasks:
        tasks = tasks[:n_tasks]

    # Generate responses
    logger.info("Generating responses for %s ...", model)
    gen = _generate_all(client, model, tasks, max_workers_gen, max_tokens, temperature, top_p, debug)

    # Judge each response individually
    logger.info("Running individual scoring with %s ...", judge_model)
    results = []
    lock = threading.Lock()

    def _judge_one(idx: int) -> Dict:
        task = tasks[idx]
        g = gen[idx]
        model_text = g["text"]
        j = judge_score(judge_client, judge_model, task, model_text)

        return {
            "session_id": task["session_id"],
            "primary_tag": task["primary_tag"],
            "model_input": g["input_messages"],
            "model_output": model_text,
            "model_usage": g["usage"],
            "judge_result": j,
            "judge_failed": j["failed"],
            "raw_score": j["raw_score"],
            "score_100": j["score_100"],
            "rescaled_score": j["rescaled_score"],
        }

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futures = {pool.submit(_judge_one, i): i for i in range(len(tasks))}
        for fut in tqdm(as_completed(futures), total=len(tasks), desc="Scoring"):
            try:
                rec = fut.result()
                with lock:
                    results.append(rec)
            except Exception as e:
                logger.warning("Error scoring task %d: %s", futures[fut], e)

    # Aggregate
    judge_failures = sum(1 for r in results if r["judge_failed"])
    raw_scores = [r["raw_score"] for r in results if not r["judge_failed"]]
    rescaled_scores = [r["rescaled_score"] for r in results if not r["judge_failed"]]

    avg_raw_score = sum(raw_scores) / len(raw_scores) if raw_scores else 0.0
    scores_100 = [r["score_100"] for r in results if not r["judge_failed"]]
    avg_score_100 = sum(scores_100) / len(scores_100) if scores_100 else 0.0
    rescaled_scores = [r["rescaled_score"] for r in results if not r["judge_failed"]]
    avg_rescaled_score = sum(rescaled_scores) / len(rescaled_scores) if rescaled_scores else 0.0

    # Per-category breakdown (using the 0-100 scale to match Table 2)
    category_scores: Dict[str, List[float]] = {}
    for r in results:
        if r["judge_failed"]:
            continue
        tag = r["primary_tag"] or "unknown"
        category_scores.setdefault(tag, []).append(r["score_100"])
    category_avg = {tag: round(sum(s) / len(s), 2) for tag, s in category_scores.items()}

    # Token usage
    model_usage_total = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
    judge_usage_total = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
    for r in results:
        for k in model_usage_total:
            v = (r.get("model_usage") or {}).get(k)
            if v is not None:
                model_usage_total[k] += v
            v = ((r.get("judge_result") or {}).get("usage") or {}).get(k)
            if v is not None:
                judge_usage_total[k] += v

    summary = {
        "model": model,
        "n_tasks": len(raw_scores),
        "wb_score_raw_avg": round(avg_raw_score, 2),
        "wb_score_100": round(avg_score_100, 2),
        "wb_score_rescaled": round(avg_rescaled_score, 2),
        "judge_failures": judge_failures,
        "judge_model": judge_model,
        "category_scores": category_avg,
        "sampling_params": {
            "temperature": temperature,
            "top_p": top_p,
        },
        "token_usage": {
            "model": model_usage_total,
            "judge": judge_usage_total,
        },
    }

    # Save
    out_prefix = f"{model.replace('/', '_')}_score"
    detail_path = Path(output_dir) / f"{out_prefix}_details.jsonl"
    summary_path = Path(output_dir) / f"{out_prefix}_summary.json"
    with open(detail_path, "w") as f:
        for r in results:
            f.write(json.dumps(r) + "\n")
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)
    logger.info("Results saved to %s", output_dir)
    _print_summary(summary)
    return {"summary": summary, "results": results}


def _print_summary(s: Dict) -> None:
    print("\n" + "=" * 60)
    print(f"WB-Score: {s['model']}")
    print("=" * 60)
    print(f"  Tasks evaluated : {s['n_tasks']}")
    print(f"  Raw avg (1-10)  : {s['wb_score_raw_avg']:.2f}")
    print(f"  WB-Score (0-100): {s['wb_score_100']:.1f}  (raw*10, as in Table 2)")
    print(f"  WB-Score rescaled: {s['wb_score_rescaled']:+.2f}  ((raw-5)*2, as in Section 3.3)")
    print(f"  Judge failures  : {s.get('judge_failures', 0)}")
    print(f"  Judge model     : {s['judge_model']}")
    sp = s.get("sampling_params", {})
    print(f"  Temperature     : {sp.get('temperature')}")
    print(f"  Top-p           : {sp.get('top_p')}")
    usage = s.get("token_usage", {})
    for who in ("model", "judge"):
        u = usage.get(who, {})
        label = s["model"] if who == "model" else f"judge({s['judge_model']})"
        print(f"  Tokens [{label}]: prompt={u.get('prompt_tokens')} completion={u.get('completion_tokens')}")
    cat = s.get("category_scores", {})
    if cat:
        print(f"  --- Per-category WB-Score ---")
        for tag, avg in sorted(cat.items(), key=lambda x: -x[1]):
            print(f"    {tag:30s}: {avg:+.2f}")
    print("=" * 60 + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="WildBench WB-Score individual evaluation.")
    parser.add_argument("--model",
                        required=True,
                        help="Model identifier to evaluate.")
    parser.add_argument("--port_model",
                        type=int, default=8000,
                        help="Port for local vLLM server for model (default 8000).")
    parser.add_argument("--judge_model",
                        required=True,
                        help="Judge model identifier.")
    parser.add_argument("--port_judge",
                        type=int, default=8002,
                        help="Port for local vLLM server for judge model (default 8002).")
    parser.add_argument("--max_workers",
                        type=int, default=40,
                        help="Thread pool concurrency for judging.")
    parser.add_argument("--max_workers_gen",
                        type=int, default=64,
                        help="Thread pool concurrency for generation.")
    parser.add_argument("--max_tokens",
                        type=int, default=2048,
                        help="Max tokens per generation.")
    parser.add_argument("--output_dir",
                        default="results", help="Directory for output files.")
    parser.add_argument("--n_tasks",
                        type=int, default=None,
                        help="Limit evaluation to first N tasks (useful for testing).")
    parser.add_argument("--temperature",
                        type=float, default=0.0,
                        help="Sampling temperature for model (default 0.0; not applied to judge).")
    parser.add_argument("--top_p",
                        type=float, default=None,
                        help="Top-p nucleus sampling for model (default: not set; not applied to judge).")
    parser.add_argument("--debug",
                        action="store_true",
                        help="Enable debug logging.")
    args = parser.parse_args()

    evaluate_score(
        model=args.model, port_model=args.port_model,
        judge_model=args.judge_model, port_judge=args.port_judge,
        max_workers=args.max_workers,
        max_workers_gen=args.max_workers_gen,
        max_tokens=args.max_tokens,
        output_dir=args.output_dir,
        n_tasks=args.n_tasks,
        temperature=args.temperature,
        top_p=args.top_p,
        debug=args.debug,
    )


if __name__ == "__main__":
    main()
