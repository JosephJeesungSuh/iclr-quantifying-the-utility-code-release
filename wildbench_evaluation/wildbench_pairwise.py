PAIRWISE_PROMPT = """\
# Instruction
You are an expert evaluator. Your task is to evaluate the quality of the responses generated by two AI models. We will provide you with the user query and a pair of AI-generated responses (Response A and B). You should first read the user query and the conversation history carefully for analyzing the task, and then evaluate the quality of the responses based on and rules provided below.

# Conversation between User and AI
## History
<|begin_of_history|>
{history}
<|end_of_history|>

## Current User Query
<|begin_of_query|>
{user_query}
<|end_of_query|>

## Response A
<|begin_of_response_A|>
{candidate_A}
<|end_of_response_A|>

## Response B
<|begin_of_response_B|>
{candidate_B}
<|end_of_response_B|>

# Evaluation
## Checklist
<|begin_of_checklist|>
{checklist}
<|end_of_checklist|>
Please use this checklist to guide your evaluation, but do not limit your assessment to the checklist.

## Rules
You should compare the above two responses based on your analysis of the user queries and the conversation history. You should first write down your analysis and the checklist that you used for the evaluation, and then provide your assessment according to the checklist. There are five choices to give your final assessment: ["A++", "A+", "A=B", "B+", "B++"], which correspond to the following meanings:

- `A++`: Response A is much better than Response B.
- `A+`: Response A is only slightly better than Response B.
- `A=B`: Response A and B are of the same quality. Please use this choice sparingly.
- `B+`: Response B is only slightly better than Response A.
- `B++`: Response B is much better than Response A.

## Output Format
First, please output your analysis for each model response, and then summarize your assessment to three aspects: "reason A=B", "reason A>B", and "reason B>A", and finally make your choice for the final assessment.

Please provide your evaluation results in the following json format by filling in the placeholders in []:
```
{{
"analysis of A": "[analysis of Response A]",
"analysis of B": "[analysis of Response B]",
"reason of A=B": "[where Response A and B perform equally well]",
"reason of A>B": "[where Response A is better than Response B]",
"reason of B>A": "[where Response B is better than Response A]",
"choice": "[A++ or A+ or A=B or B+ or B++]"
}}
```

IMPORTANT: You must output a valid JSON block with the "choice" field set to exactly one of: A++, A+, A=B, B+, B++."""

def _get_client(model: str, port: int) -> OpenAI:

    if model.lower().startswith("claude"):
        logger.info(f"Using Anthropic API client for model {model}")
        return OpenAI(
            api_key=os.environ["ANTHROPIC_API_KEY"],
            base_url="https://api.anthropic.com/v1/",
        )

    if model.lower().startswith("gpt"):
        logger.info(f"Using OpenAI API client for model {model}")
        return OpenAI(
            api_key=os.environ["OPENAI_API_KEY"]
        )
    
    if model.lower().startswith("gemini"):
        logger.info(f"Using Gemini API client for model {model}")
        return OpenAI(
            api_key=os.environ.get("GEMINI_API_KEY"),
            base_url="https://generativelanguage.googleapis.com/v1beta/openai/",
        )

    logger.info(f"Using custom OpenAI-compatible client for model {model}")
    client = OpenAI(
        base_url="http://localhost:{port}/v1".format(port=port)
    )
    try:
        models_list = client.models.list()
        model_ids = [m.id for m in models_list.data]
        if model not in model_ids:
             logger.warning(f"Model {model} not found in the server's model list: {model_ids}")
    except Exception as e:
        logger.warning(f"Error connecting to custom client for model {model} on port {port}: {e}")
    return client


def load_custom_dataset(path: str) -> List[Dict]:
    """
    Load a custom WildBench-style dataset from a JSONL file produced by generate_rubrics.py.
    Each line must have: session_id, user_query, history (formatted string), checklist (list).
    """
    def _parse_history_string(history_str: str) -> List[Dict]:
        """Convert 'Human: ...\n\nAI: ...' formatted string back to a list of turn dicts."""
        if not history_str or history_str.strip() == "(No prior conversation history.)":
            return []
        turns = []
        role_map = {"Human": "user", "AI": "assistant"}
        # Split on blank lines between turns
        for chunk in re.split(r"\n\n(?=Human:|AI:)", history_str.strip()):
            for prefix, role in role_map.items():
                if chunk.startswith(prefix + ": "):
                    content = chunk[len(prefix) + 2:]
                    turns.append({"role": role, "content": content})
                    break
        return turns

    logger.info("Loading custom dataset from %s …", path)
    tasks = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            item = json.loads(line)
            history_list = _parse_history_string(item.get("history", ""))
            tasks.append(
                {
                    "session_id": item["session_id"],
                    "conversation_hash": item.get("conversation_hash"),
                    "history": item.get("history", "(No prior conversation history.)"),
                    "history_list": history_list,
                    "user_query": item["user_query"],
                    "checklist": item["checklist"],
                    "primary_tag": item.get("primary_tag"),
                }
            )
    logger.info("Loaded %d tasks from custom dataset.", len(tasks))
    return tasks


def load_wildbench(split: str = "test") -> List[Dict]:
    """
    Load WildBench v2 from HuggingFace and return list of task dicts.
    """
    def _format_history(turns: List[Dict]) -> str:
        if not turns:
            return "(No prior conversation history.)"
        lines = []
        for t in turns:
            role = "Human" if t["role"] == "user" else "AI"
            lines.append(f"{role}: {t['content']}")
        return "\n\n".join(lines)

    logger.info("Loading WildBench v2 dataset …")
    ds = load_dataset("allenai/WildBench", "v2", split=split)
    tasks = []
    for item in ds:
        turns = item["conversation_input"]
        last_user_idx = max(i for i, t in enumerate(turns) if t["role"] == "user")
        history_turns = turns[:last_user_idx]
        current_query = turns[last_user_idx]["content"]
        history_text = _format_history(history_turns)
        tasks.append(
            {
                "session_id": item["session_id"],
                "history": history_text,
                "history_list": history_turns,
                "user_query": current_query,
                "checklist": item["checklist"],
                "primary_tag": item.get("primary_tag"),
            }
        )
    logger.info("Loaded %d tasks.", len(tasks))
    return tasks


def _generate_all(
    client: OpenAI, model: str,
    tasks: List[Dict],
    max_workers: int,
    max_tokens: int, temperature: float = 0.0, top_p: Optional[float] = None,
    debug: bool = False,
) -> List[Dict]:
    """
    Generate responses for all tasks, return list of dicts aligned with tasks.
    Each dict has 'text', 'usage', and 'input_messages'.
    """
    responses: List[Optional[Dict]] = [None] * len(tasks)
    lock = threading.Lock()

    def _gen(idx: int) -> None:
        task = tasks[idx]
        result = generate_response(
            client, model, task["history_list"], task["user_query"],
            max_tokens, temperature, top_p=top_p,
        )
        with lock:
            responses[idx] = result

    if debug:
        for i in range(len(tasks)):
            result = generate_response(
                client, model, tasks[i]["history_list"], tasks[i]["user_query"],
                max_tokens, temperature, top_p=top_p, debug=debug,
            )

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futures = [pool.submit(_gen, i) for i in range(len(tasks))]
        for fut in tqdm(as_completed(futures), total=len(tasks), desc=f"Generating [{model}]"):
            try:
                fut.result()
            except Exception as e:
                logger.warning("Generation error: %s", e)

    return responses


def generate_response(
    client: OpenAI, model: str,
    history: List[Dict],
    user_query: str,
    max_tokens: int = 2048, temperature: float = 0.0, top_p: Optional[float] = None,
    max_retries: int = 8,
    debug: bool = False,
) -> Dict:
    """
    Generate a single model response for a WildBench task.
    Returns a dict with 'text', 'usage', and 'input_messages'.
    """
    messages = _build_messages(history, user_query)
    
    extra_kwargs: Dict = {}
    if top_p is not None:
        extra_kwargs["top_p"] = top_p
    if model.lower().startswith("gpt"):
        if model.lower().startswith("gpt-5"):
            extra_kwargs["reasoning_effort"] = "minimal"
        extra_kwargs["max_completion_tokens"] = max_tokens
    else:
        extra_kwargs["max_tokens"] = max_tokens
    if model.lower().startswith("gemini"):
        extra_kwargs["extra_body"] = {"reasoning_effort": "none"}
    
    last_exc = None
    for _ in range(max_retries):
        try:
            if debug:
                import pdb; pdb.set_trace()
            resp = client.chat.completions.create(
                model=model,
                messages=messages,
                temperature=temperature,
                **extra_kwargs,
            )
            if debug:
                import pdb; pdb.set_trace()
            usage = resp.usage
            return {
                "text": resp.choices[0].message.content,
                "usage": {
                    "prompt_tokens": usage.prompt_tokens if usage else None,
                    "completion_tokens": usage.completion_tokens if usage else None,
                    "total_tokens": usage.total_tokens if usage else None,
                },
                "input_messages": messages,
            }
        except Exception as e:
            last_exc = e
    logger.warning("Generation error for model %s: %s", model, last_exc)
    return {
        "text": "Failed to generate response.",
        "usage": {"prompt_tokens": None, "completion_tokens": None, "total_tokens": None},
        "input_messages": messages,
    }


def _build_messages(history: List[Dict],
                    user_query: str) -> List[Dict]:
    messages: List[Dict] = []
    _expected_role = "user"
    for uttr in history:
        _role = uttr["role"]
        assert _role == _expected_role, f"Expected role {_expected_role} but got {_role} in history"
        messages.append(
            {"role": _role, "content": uttr["content"]}
        )
        _expected_role = "assistant" if _expected_role == "user" else "user"
    messages.append(
        {"role": "user", "content": user_query}
    )
    return messages


def _extract_json_choice(text: str) -> Optional[str]:
    """
    Extract the 'choice' field from the judge's JSON response.
    """
    code_block = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    raw = code_block.group(1) if code_block else text
    try: # Try strict JSON parse first
        data = json.loads(raw)
        return data.get("choice", "").strip()
    except json.JSONDecodeError:
        pass

    # Fallback: regex for "choice": "..."
    m = re.search(r'"choice"\s*:\s*"([^"]+)"', raw)
    if m:
        return m.group(1).strip()

    # Last resort: look for a choice token as a standalone word (not substring)
    # Check longer tokens first to avoid "A+" matching inside "A++"
    for token in ["A++", "B++", "A=B", "A+", "B+"]:
        # Match token not preceded/followed by + or = to avoid substring matches
        pattern = re.escape(token)
        if re.search(rf'(?<![+=]){pattern}(?![+=])', text):
            return token
    return None


def judge_pair(
    judge_client: OpenAI, judge_model: str,
    task: Dict,
    response_A: str, response_B: str,
    length_penalty_K: int = 500,
    max_retries: int = 8,
) -> Dict:
    """
    Ask the judge to compare response_A vs response_B.
    Returns a dict with 'raw_choice', 'penalized_choice', 'score',
    'raw_output', 'usage', and 'input_messages'.
    Score from perspective of A: +1 / +0.5 / 0 / -0.5 / -1.
    """
    checklist_str = "\n".join(f"- {q}" for q in task["checklist"])
    prompt = PAIRWISE_PROMPT.format(
        history=task["history"],
        user_query=task["user_query"],
        candidate_A=response_A,
        candidate_B=response_B,
        checklist=checklist_str,
    )
    judge_messages = [{"role": "user", "content": prompt}]

    raw_choice = None
    raw_output = ""
    judge_usage: Dict = {"prompt_tokens": None, "completion_tokens": None, "total_tokens": None}
    extra_kwargs = {}

    extra_kwargs: Dict = {}
    if judge_model.lower().startswith("gpt"):
        if judge_model.lower().startswith("gpt-5"):
            extra_kwargs["reasoning_effort"] = "minimal"
        extra_kwargs["max_completion_tokens"] = 16384
    else:
        extra_kwargs["max_tokens"] = 16384
    if judge_model.lower().startswith("gemini"):
        extra_kwargs["extra_body"] = {"reasoning_effort": "none"}
    elif "qwen3" in judge_model.lower():
        extra_kwargs["extra_body"] = {"chat_template_kwargs": {"enable_thinking": False}}


    for _retry in range(max_retries):
        try:
            # Use small temperature on retries so we don't get identical bad outputs
            retry_temp = 0.0 if _retry == 0 else 0.3
            resp = judge_client.chat.completions.create(
                model=judge_model,
                messages=judge_messages,
                temperature=1 if judge_model.lower().startswith("gpt-5") else retry_temp,
                **extra_kwargs,
            )
            raw_output = resp.choices[0].message.content or ""
            usage = resp.usage
            if usage:
                judge_usage = {
                    "prompt_tokens": usage.prompt_tokens,
                    "completion_tokens": usage.completion_tokens,
                    "total_tokens": usage.total_tokens,
                }
            extracted = _extract_json_choice(raw_output)
            if extracted:
                raw_choice = extracted
                break
            else:
                logger.warning("Judge retry %d/%d: could not extract choice from output (first 2000 chars): %s",
                               _retry + 1, max_retries, raw_output[:2000])
        except Exception as e:
            logger.warning("Judge retry %d/%d error: %s", _retry + 1, max_retries, e)
            time.sleep(_retry * 2 + 0.5)

    failed = raw_choice is None
    if failed:
        return {
            "raw_choice": None,
            "penalized_choice": None,
            "score": None,
            "raw_output": raw_output,
            "usage": judge_usage,
            "input_messages": judge_messages,
            "failed": True,
        }

    penalized_choice = _apply_length_penalty(
        raw_choice, response_A, response_B, length_penalty_K
    )
    score = _choice_to_score(penalized_choice)

    return {
        "raw_choice": raw_choice,
        "penalized_choice": penalized_choice,
        "score": score,
        "raw_output": raw_output,
        "usage": judge_usage,
        "input_messages": judge_messages,
        "failed": False,
    }


def _apply_length_penalty(
    choice: str, response_A: str, response_B: str, K: int
) -> str:
    """
    Downgrade 'slightly better' to tie if the winner is >K chars longer.
    """
    if K <= 0:
        return choice
    len_A, len_B = len(response_A), len(response_B)
    if choice == "A+" and (len_A - len_B) > K:
        return "A=B"
    if choice == "B+" and (len_B - len_A) > K:
        return "A=B"
    return choice


def _choice_to_score(choice: str) -> float:
    return {"A++": 1.0, "A+": 0.5, "A=B": 0.0, "B+": -0.5, "B++": -1.0}.get(
        choice, 0.0
    )


def evaluate_pair(
    model1: str,
    model2: str,
    judge_model: str,
    port_model1: int = 8000,
    port_model2: int = 8001,
    port_judge: int = 8002,
    length_penalty_K: int = 500,
    max_workers: int = 8,
    max_workers_gen: int = 8,
    max_tokens: int = 2048,
    output_dir: str = "results",
    n_tasks: Optional[int] = None,
    swap_positions: bool = True,
    temperature: float = 0.0,
    top_p: Optional[float] = None,
    debug: bool = False,
    input_file: Optional[str] = None,
    flush_every: int = 500,
) -> Dict:
    """
    Run WB-Reward pairwise evaluation of model1 vs model2.
    Returns
        dict with 'win_rate', 'reward', and per-task results.
    """
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    client1 = _get_client(model1, port_model1)
    client2 = _get_client(model2, port_model2)
    judge_client = _get_client(judge_model, port_judge)
    tasks = load_custom_dataset(input_file) if input_file else load_wildbench()
    if n_tasks:
        tasks = tasks[:n_tasks]

    out_prefix = f"{model1.replace('/', '_')}_vs_{model2.replace('/', '_')}"
    gen_cache_path = Path(output_dir) / f"{out_prefix}_generations.jsonl"

    # generation before pairwise judge — skip if cache exists
    if gen_cache_path.exists():
        logger.info("Loading cached generations from %s (skipping generation step) …", gen_cache_path)
        gen1 = [None] * len(tasks)
        gen2 = [None] * len(tasks)
        session_to_idx = {t["session_id"]: i for i, t in enumerate(tasks)}
        with open(gen_cache_path) as _f:
            for _line in _f:
                _line = _line.strip()
                if not _line:
                    continue
                _rec = json.loads(_line)
                _idx = session_to_idx.get(_rec["session_id"])
                if _idx is not None:
                    _task = tasks[_idx]
                    _cached_hash = _rec.get("conversation_hash")
                    _task_hash = _task.get("conversation_hash")
                    if _cached_hash is not None and _task_hash is not None and _cached_hash != _task_hash:
                        logger.warning(
                            "conversation_hash mismatch for session %s (cached=%s, current=%s); skipping cache entry.",
                            _rec["session_id"], _cached_hash, _task_hash,
                        )
                        continue
                    gen1[_idx] = _rec["gen1"]
                    gen2[_idx] = _rec["gen2"]
        missing = sum(1 for g in gen1 if g is None)
        if missing:
            logger.warning("%d tasks have no cached generation; they will produce empty results.", missing)
            for i in range(len(tasks)):
                if gen1[i] is None:
                    gen1[i] = {"text": "", "usage": {}, "input_messages": []}
                if gen2[i] is None:
                    gen2[i] = {"text": "", "usage": {}, "input_messages": []}
    else:
        logger.info("Generating responses for %s and %s in parallel …", model1, model2)
        if debug:
            gen1 = _generate_all(client1, model1, tasks, 1, max_tokens, temperature, top_p, debug)
            gen2 = _generate_all(client2, model2, tasks, 1, max_tokens, temperature, top_p, debug)
        with ThreadPoolExecutor(max_workers=2) as pool:
            fut1 = pool.submit(_generate_all, client1, model1, tasks, max_workers_gen, max_tokens, temperature, top_p)
            fut2 = pool.submit(_generate_all, client2, model2, tasks, max_workers_gen, max_tokens, temperature, top_p)
            gen1 = fut1.result()
            gen2 = fut2.result()
        logger.info("Saving generations cache to %s …", gen_cache_path)
        with open(gen_cache_path, "w") as _f:
            for i, task in enumerate(tasks):
                _f.write(json.dumps({
                    "session_id": task["session_id"],
                    "conversation_hash": task.get("conversation_hash"),
                    "gen1": gen1[i],
                    "gen2": gen2[i],
                }) + "\n")

    # Paths for judge output (out_prefix already set above for gen_cache_path)
    detail_path = Path(output_dir) / f"{out_prefix}_details.jsonl"
    summary_path = Path(output_dir) / f"{out_prefix}_summary.json"

    # Load existing (partial) judge output for resume
    results: List[Dict] = []
    existing_sessions: set = set()
    if detail_path.exists():
        logger.info("Found existing judge output at %s — loading for resume …", detail_path)
        with open(detail_path) as _rf:
            for _line in _rf:
                _line = _line.strip()
                if not _line:
                    continue
                _rec = json.loads(_line)
                results.append(_rec)
                existing_sessions.add(_rec["session_id"])
        logger.info("Loaded %d existing judge results; %d tasks remain.", len(existing_sessions), len(tasks) - len(existing_sessions))

    tasks_to_judge = [i for i, t in enumerate(tasks) if t["session_id"] not in existing_sessions]

    # judge with generated ones
    logger.info("Running pairwise judgement with %s …", judge_model)
    lock = threading.Lock()
    flush_buffer: List[Dict] = []

    def _do_flush() -> None:
        """Append flush_buffer contents to detail_path. Must be called with lock held."""
        with open(detail_path, "a") as _wf:
            for _r in flush_buffer:
                _wf.write(json.dumps(_r) + "\n")
        flush_buffer.clear()

    def _judge_one(idx: int) -> Dict:
        task = tasks[idx]
        g1, g2 = gen1[idx], gen2[idx]
        r1, r2 = g1["text"], g2["text"]
        j1 = judge_pair(judge_client, judge_model, task, r1, r2, length_penalty_K)
        j2 = None
        judge_failed = j1["failed"]

        if swap_positions:
            j2 = judge_pair(judge_client, judge_model, task, r2, r1, length_penalty_K)
            judge_failed = judge_failed or j2["failed"]

        if judge_failed:
            score_m1 = None
            logger.warning("Judge failed for session %s (order1_failed=%s, order2_failed=%s)",
                           task["session_id"], j1["failed"], j2["failed"] if j2 else "n/a")
        else:
            score_m1 = j1["score"]
            if swap_positions:
                score_m1 = (score_m1 + (-j2["score"])) / 2.0

        return {
            "session_id": task["session_id"],
            "primary_tag": task["primary_tag"],
            "model1_input": g1["input_messages"],
            "model1_output": r1,
            "model1_usage": g1["usage"],
            "model2_input": g2["input_messages"],
            "model2_output": r2,
            "model2_usage": g2["usage"],
            "judge_order1": j1,
            "judge_order2": j2,
            "judge_failed": judge_failed,
            "final_score_model1": score_m1,
        }

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futures = {pool.submit(_judge_one, i): i for i in tasks_to_judge}
        for fut in tqdm(as_completed(futures), total=len(tasks_to_judge), desc="Judging"):
            try:
                rec = fut.result()
                with lock:
                    results.append(rec)
                    flush_buffer.append(rec)
                    if len(flush_buffer) >= flush_every:
                        logger.info("Flushing %d judge results to %s …", len(flush_buffer), detail_path)
                        _do_flush()
            except Exception as e:
                logger.warning("Error judging task %d: %s", futures[fut], e)

    # Flush any remaining results not yet written
    with lock:
        if flush_buffer:
            logger.info("Flushing remaining %d judge results to %s …", len(flush_buffer), detail_path)
            _do_flush()

    # aggregate to get stats (exclude tasks where the judge failed)
    judge_failures = sum(1 for r in results if r["judge_failed"])
    scores = [r["final_score_model1"] for r in results if not r["judge_failed"]]
    avg_reward = sum(scores) / len(scores) if scores else 0.0

    wins = sum(1 for s in scores if s > 0)
    ties = sum(1 for s in scores if s == 0)
    losses = sum(1 for s in scores if s < 0)
    win_rate = wins / len(scores) if scores else 0.0

    # aggregate token usage across all tasks
    def _sum_usage(key: str, order_key: Optional[str] = None) -> Dict:
        total = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
        for r in results:
            src = r[key] if order_key is None else (r[key] or {}).get("usage", {})
            for k in total:
                v = src.get(k) if src else None
                if v is not None:
                    total[k] += v
        return total

    judge_usage_order1 = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
    judge_usage_order2 = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}
    for r in results:
        for k in judge_usage_order1:
            v1 = (r["judge_order1"] or {}).get("usage", {}).get(k)
            if v1 is not None:
                judge_usage_order1[k] += v1
            if r["judge_order2"] is not None:
                v2 = (r["judge_order2"] or {}).get("usage", {}).get(k)
                if v2 is not None:
                    judge_usage_order2[k] += v2

    summary = {
        "model1": model1,
        "model2": model2,
        "n_tasks": len(scores),
        "wb_reward": round(avg_reward * 100, 2),
        "win_rate": round(win_rate * 100, 2),
        "wins": wins,
        "ties": ties,
        "losses": losses,
        "judge_failures": judge_failures,
        "length_penalty_K": length_penalty_K,
        "judge_model": judge_model,
        "swap_positions": swap_positions,
        "sampling_params": {
            "temperature": temperature,
            "top_p": top_p,
        },
        "token_usage": {
            "model1": _sum_usage("model1_usage"),
            "model2": _sum_usage("model2_usage"),
            "judge_order1": judge_usage_order1,
            "judge_order2": judge_usage_order2,
        },
    }

    # Save summary (detail_path already written via incremental flushes above)
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)
    logger.info("Results saved to %s", output_dir)
    _print_summary(summary)
    return {"summary": summary, "results": results}


def _print_summary(s: Dict) -> None:
    print("\n" + "=" * 60)
    print(f"WB-Reward: {s['model1']}  vs  {s['model2']}")
    print("=" * 60)
    print(f"  Tasks evaluated : {s['n_tasks']}")
    print(f"  WB-Reward       : {s['wb_reward']:+.2f}")
    print(f"  Win rate (m1)   : {s['win_rate']:.1f}%")
    print(f"  Wins / Ties / Losses : {s['wins']} / {s['ties']} / {s['losses']}")
    print(f"  Judge failures  : {s.get('judge_failures', 0)}")
    print(f"  Judge model     : {s['judge_model']}")
    print(f"  Length penalty K: {s['length_penalty_K']}")
    sp = s.get("sampling_params", {})
    print(f"  Temperature     : {sp.get('temperature')}")
    print(f"  Top-p           : {sp.get('top_p')}")
    usage = s.get("token_usage", {})
    for who in ("model1", "model2", "judge_order1", "judge_order2"):
        u = usage.get(who, {})
        label = {"model1": s["model1"], "model2": s["model2"],
                 "judge_order1": f"judge(order1)", "judge_order2": f"judge(order2)"}.get(who, who)
        print(f"  Tokens [{label}]: prompt={u.get('prompt_tokens')} completion={u.get('completion_tokens')}")
    print("=" * 60 + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="WildBench WB-Reward pairwise evaluation.")
    parser.add_argument("--model1",
                        required=True,
                        help="First model identifier.")
    parser.add_argument("--port_model1",
                        type=int, default=8000,
                        help="Port for local vLLM server for model1 (default 8000).")
    parser.add_argument("--model2",
                        required=True,
                        help="Second model identifier.")
    parser.add_argument("--port_model2",
                        type=int, default=8001,
                        help="Port for local vLLM server for model2 (default 8001).")
    parser.add_argument("--judge_model",
                        required=True,
                        help="Judge model identifier.")
    parser.add_argument("--port_judge",
                        type=int, default=8002,
                        help="Port for local vLLM server for judge model (default 8002).")
    parser.add_argument("--length_penalty_K",
                        type=int, default=500,
                        help="Chars threshold for length penalty (default 500; use 0 to disable).")
    parser.add_argument("--max_workers",
                        type=int, default=40,
                        help="Thread pool concurrency.")
    parser.add_argument("--max_workers_gen",
                        type=int, default=64,
                        help="Thread pool concurrency for generation.")
    parser.add_argument("--max_tokens",
                        type=int, default=2048,
                        help="Max tokens per generation.")
    parser.add_argument("--output_dir",
                        default="results", help="Directory for output files.")
    parser.add_argument("--n_tasks",
                        type=int, default=None,
                        help="Limit evaluation to first N tasks (useful for testing).")
    parser.add_argument("--no_swap",
                        action="store_true",
                        help="Disable swapped-position evaluation (single order only).")
    parser.add_argument("--temperature",
                        type=float, default=0.0,
                        help="Sampling temperature for model1 and model2 (default 0.0; not applied to judge).")
    parser.add_argument("--top_p",
                        type=float, default=None,
                        help="Top-p nucleus sampling for model1 and model2 (default: not set; not applied to judge).")
    parser.add_argument("--debug",
                        action="store_true",
                        help="Enable debug logging.")
    parser.add_argument("--input_file",
                        default=None,
                        help="Path to a custom JSONL dataset (e.g. from generate_rubrics.py). "
                             "If not set, the standard WildBench v2 dataset is used.")
    parser.add_argument("--flush_every",
                        type=int, default=500,
                        help="Flush judge results to disk every N completed tasks (default 500). "
                             "Also used for resuming from a partial output file.")
    args = parser.parse_args()

    evaluate_pair(
        model1=args.model1, port_model1=args.port_model1,
        model2=args.model2, port_model2=args.port_model2,
        judge_model=args.judge_model, port_judge=args.port_judge,
        length_penalty_K=args.length_penalty_K,
        max_workers=args.max_workers,
        max_workers_gen=args.max_workers_gen,
        max_tokens=args.max_tokens,
        output_dir=args.output_dir,
        n_tasks=args.n_tasks,
        swap_positions=not args.no_swap,
        temperature=args.temperature,
        top_p=args.top_p,
        debug=args.debug,
        input_file=args.input_file,
        flush_every=args.flush_every,
    )


if __name__ == "__main__":
    main()
