"""
WildBench Pairwise Evaluation (WB-Reward)
==========================================
Reproduces the dynamic rubric-based pairwise win-rate protocol from:
  "WildBench: Benchmarking LLMs with Challenging Tasks from Real Users in the Wild"
  Lin et al., 2024  (arXiv 2406.04770)

Usage:
    python wildbench_pairwise.py --model1 gpt-4o --model2 gpt-4o-mini

Each argument is a model identifier supported by one of:
  - OpenAI API  (e.g. gpt-4o, gpt-4o-mini, gpt-4-turbo)
  - Anthropic API  (e.g. claude-3-5-sonnet-20241022)
  - Local vLLM server  (pass --model1 <model_name> --base_url1 http://localhost:8000/v1)

Protocol (Section 3.2 of the paper):
  1. Load WildBench v2 (1 024 tasks with per-task checklists).
  2. Generate one response per model for each task.
  3. For each task, ask GPT-4-Turbo to compare the two responses using the
     task-specific checklist (Appendix D prompt).
  4. Score: +1 (A>>B), +0.5 (A>B), 0 (A=B), -0.5 (A<B), -1 (A<<B).
  5. Length penalty: if the winning response is >K chars longer than the losing
     one, downgrade "slightly better/worse" to "tie" (default K=500).
  6. To reduce position bias, run evaluation in both orders (A=model1/B=model2
     and A=model2/B=model1) and average.
"""

