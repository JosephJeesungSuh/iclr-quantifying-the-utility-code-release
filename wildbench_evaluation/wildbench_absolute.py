"""
WildBench Individual Evaluation (WB-Score)
==========================================
Reproduces the individual scoring protocol from:
  "WildBench: Benchmarking LLMs with Challenging Tasks from Real Users in the Wild"
  Lin et al., 2024  (arXiv 2406.04770)

Usage:
    python wildbench_score.py --model gpt-4o --judge_model gpt-4o

Each argument is a model identifier supported by one of:
  - OpenAI API  (e.g. gpt-4o, gpt-4o-mini, gpt-4-turbo)
  - Anthropic API  (e.g. claude-3-5-sonnet-20241022)
  - Local vLLM server  (pass --model <model_name> --port_model <port>)

Protocol (Section 3.3 of the paper):
  1. Load WildBench v2 (1,024 tasks with per-task checklists).
  2. Generate one response per model for each task.
  3. For each task, ask the judge LLM to score the response individually
     on a 1-10 scale using the task-specific checklist (Appendix E prompt).
  4. Rescale: S' = (S - 5) * 2, so a borderline score of 5 maps to 0.
  5. WB-Score = average of rescaled scores across all tasks.
"""

